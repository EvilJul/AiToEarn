test('enterprise AI arrangement keeps source and generation provenance', async ({ page }) => {
  const generationId = '888888888888888888888888'
  const knowledgeId = 'dddddddddddddddddddddddd'
  await page.route('**/api/enterprise-ops/enterprises/*/generations**', route => route.fulfill({ contentType: 'application/json', body: JSON.stringify({ code: 0, message: 'success', data: { id: generationId, taskId: generationId, status: 'ready', knowledgeIds: [knowledgeId], topicId: '', draft: { title: '已批准的企业服务范围', body: '提供企业内容运营服务，实际报价由销售确认。', layout: 'cover', missingCategories: ['price'] } } }) }))
  await page.goto('/zh-CN/enterprise')
  await page.getByRole('button', { name: '内容与审核', exact: true }).click()
  await page.getByRole('button', { name: '创作图文', exact: true }).click()
  await page.getByRole('checkbox').first().click()
  const request = page.waitForRequest(req => req.url().endsWith('/generations') && req.method() === 'POST')
  await page.getByRole('button', { name: '根据所选资料生成', exact: true }).click()
  expect((await request).postDataJSON()).toMatchObject({ knowledgeIds: [knowledgeId] })
  await page.getByRole('button', { name: '使用这份文案', exact: true }).click()
  await expect(page.getByLabel('标题', { exact: true })).toHaveValue('已批准的企业服务范围')
  const saved = page.waitForRequest(req => req.url().endsWith('/revisions') && req.method() === 'POST')
  await page.getByRole('button', { name: '保存草稿', exact: true }).click()
  expect((await saved).postDataJSON()).toMatchObject({ generationId, knowledgeIds: [knowledgeId] })
})
